    @classmethod
    def find_canonical_field(cls, term: str) -> Optional[str]:
        """Looks up a regional term or header and returns the canonical key."""
        if not term:
            return None
        clean = term.strip().lower()
        # Direct key match
        if clean in cls.CANONICAL_FIELDS:
            return clean

        for canon_key, synonyms in cls.TERM_MAPPINGS.items():
            for syn in synonyms:
                if syn.lower() in clean or clean in syn.lower():
                    return canon_key
        return None
